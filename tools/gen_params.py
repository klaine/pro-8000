#!/usr/bin/env python3
"""Writes the parameter tables from tools/params.json (the list a controller reaches, with its NRPN ids; 0.10.0):
src/params.h for the firmware, tools/web/params.js for the pages, and the PARAMS block in tools/pro800.py and
tools/pro800.swift. Run it after changing params.json; tools/test_pro800.py checks the outputs are fresh, so the
firmware build and the simulator's stay free of Python.

    python tools/gen_params.py           write them
    python tools/gen_params.py --check   exit 1 if any is stale (writes nothing)
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
BEGIN, END = "BEGIN PARAMS (tools/gen_params.py)", "END PARAMS"
KINDS = ["knob", "signed", "raw", "bool"]
SCOPES = ["layer", "shared", "patch", "ui"]


def load():
    with open(os.path.join(HERE, "params.json"), encoding="utf-8") as f:
        params = json.load(f)["params"]
    ids = [p["id"] for p in params]
    assert ids == sorted(set(ids)) and all(0 <= i < 128 for i in ids), "ids: unique, ascending, 0-127"
    names = [p["name"] for p in params]
    assert len(names) == len(set(names)), "names: unique"
    for p in params:
        assert p["kind"] in KINDS and p["scope"] in SCOPES, p
        assert p["kind"] == "knob" or 1 <= len(p["code"].replace(".", "")) <= 4, p
    return params


def c_table(params):
    count = params[-1]["id"] + 1
    rows = []
    for p in params:
        t = p["target"]
        if "param" in t:
            target, index = "PARAM_TARGET_KNOB", str(t["param"])
        elif "switch" in t:
            target, index = "PARAM_TARGET_SWITCH", str(t["switch"])
        elif "envmode" in t:
            target, index = "PARAM_TARGET_ENV_MODE", str(t["envmode"])
        else:
            target, index = "PARAM_TARGET_SETTING", t["setting"]
        link = 1 + t["env"] if "env" in t else 5 + t["lfo"] if "lfo" in t else 0
        rows.append("    [%d] = {PARAM_KIND_%s, PARAM_SCOPE_%s, %s, %s, %d, %d, %d, %d, %d, %d, %d, \"%s\"}, // %s"
                    % (p["id"], p["kind"].upper(), p["scope"].upper(), target, index, t.get("stride", 0), t.get("shift", 0),
                       t.get("width", 0), link, p["min"], p["max"], t.get("bias", 0), p["code"], p["name"]))
    return "\n".join([
        "// The parameters a controller reaches, by NRPN id (LSB; the MSB is the layer rule). Generated by tools/gen_params.py",
        "// from tools/params.json: change that and run the generator, never this file. Include it after main.c's SET_* ids.",
        "#ifndef PARAMS_H",
        "#define PARAMS_H",
        "",
        "#include <stdint.h>",
        "",
        "enum { PARAM_KIND_NONE, PARAM_KIND_KNOB, PARAM_KIND_SIGNED, PARAM_KIND_RAW, PARAM_KIND_BOOL };",
        "enum { PARAM_SCOPE_LAYER, PARAM_SCOPE_SHARED, PARAM_SCOPE_PATCH, PARAM_SCOPE_UI };",
        "enum { PARAM_TARGET_KNOB, PARAM_TARGET_SWITCH, PARAM_TARGET_SETTING, PARAM_TARGET_ENV_MODE };",
        "",
        "// target: the knob's parameter, the switch, layer 1's SET_* id (layer 2's is `stride` further on; 0: one for the",
        "// patch) or the envelope (0 amp, 1 filter, 2 Env 3, 3 Env 4). A field of a setting is `width` bits from `shift`",
        "// (0: the whole value); the setting holds value + bias. link: the layer a linked layer 2 reads it from, 1 + the",
        "// envelope or 5 + the LFO (0: its own). A knob's value is 0-16383; the others' min to max, as the display shows.",
        "typedef struct {",
        "    uint8_t kind, scope, target, index, stride, shift, width, link;",
        "    int16_t min, max;",
        "    int8_t bias;",
        "    char code[6];",
        "} param_def_t;",
        "",
        "#define PARAM_IDS %d" % count,
        "static const param_def_t param_defs[PARAM_IDS] = {",
        *rows,
        "};",
        "",
        "#endif",
        "",
    ])


def js_list(params):
    out = ["// The parameters a controller reaches, by NRPN id (LSB; the MSB is the layer rule: 0 the edit layer, 1 layer 1,",
           "// 2 layer 2, 3 both). Generated by tools/gen_params.py from tools/params.json: don't edit. A classic script, as",
           "// sound-plan.js: one global, PARAMS.",
           "const PARAMS = ["]
    for p in params:
        out.append("  " + json.dumps({k: p[k] for k in ("id", "name", "label", "code", "scope", "kind", "min", "max", "values") if k in p},
                                     ensure_ascii=False) + ",")
    out += ["];", ""]
    return "\n".join(out)


def py_block(params):
    rows = ["# " + BEGIN + ": id, name, kind, scope, min, max, value names",
            "PARAMS = ["]
    for p in params:
        rows.append("    (%d, %s, %s, %s, %d, %d, %s)," % (p["id"], json.dumps(p["name"]), json.dumps(p["kind"]),
                                                            json.dumps(p["scope"]), p["min"], p["max"],
                                                            json.dumps(p.get("values", []), ensure_ascii=False)))
    rows += ["]", "# " + END]
    return "\n".join(rows)


def swift_block(params):
    rows = ["// " + BEGIN + ": id, name, kind, scope, min, max, value names",
            "let paramTable: [(id: Int, name: String, kind: String, scope: String, min: Int, max: Int, values: [String])] = ["]
    for p in params:
        rows.append("    (%d, %s, %s, %s, %d, %d, [%s])," % (p["id"], json.dumps(p["name"]), json.dumps(p["kind"]),
                                                              json.dumps(p["scope"]), p["min"], p["max"],
                                                              ", ".join(json.dumps(v, ensure_ascii=False) for v in p.get("values", []))))
    rows += ["]", "// " + END]
    return "\n".join(rows)


def md_block(params):
    scope = {"layer": "per layer", "shared": "both layers", "patch": "the patch", "ui": "the panel"}
    rows = ["<!-- " + BEGIN + " -->", "", "| Id | Name | What | Values | Display |", "|---|---|---|---|---|"]
    for p in params:
        if p["kind"] == "knob":
            values = "0-16383 (CC 6 alone: 0-127)"
        elif p.get("values"):
            values = ", ".join("%d %s" % (i + p["min"], v) for i, v in enumerate(p["values"]))
        elif p["kind"] == "bool":
            values = "0 off, 1 on"
        else:
            values = "%d to %d" % (p["min"], p["max"])
        rows.append("| %d | `%s` | %s (%s) | %s | %s |" % (p["id"], p["name"], p["label"], scope[p["scope"]], values,
                                                         "as its knob" if p["kind"] == "knob" else "`%s`" % p["code"]))
    rows += ["", "<!-- " + END]
    return "\n".join(rows)


def splice(text, block, comment):
    begin, end = text.index(comment + " " + BEGIN), text.index(comment + " " + END)
    return text[:begin] + block + text[end + len(comment + " " + END):]


def outputs(params):
    files = {os.path.join(ROOT, "src", "params.h"): c_table(params), os.path.join(HERE, "web", "params.js"): js_list(params)}
    for name, block, comment in (("pro800.py", py_block(params), "#"), ("pro800.swift", swift_block(params), "//"),
                                 (os.path.join("..", "MANUAL.md"), md_block(params), "<!--")):
        path = os.path.normpath(os.path.join(HERE, name))
        with open(path, encoding="utf-8", newline="") as f:
            files[path] = splice(f.read(), block, comment)
    return files


def main(argv):
    stale = []
    for path, text in outputs(load()).items():
        old = open(path, encoding="utf-8", newline="").read() if os.path.exists(path) else None
        if old != text:
            stale.append(os.path.relpath(path, ROOT))
            if "--check" not in argv:
                with open(path, "w", encoding="utf-8", newline="") as f:
                    f.write(text)
    if "--check" in argv and stale:
        print("stale: " + ", ".join(stale) + " (run python tools/gen_params.py)")
        return 1
    print(("wrote " + ", ".join(stale)) if stale else "all fresh")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
